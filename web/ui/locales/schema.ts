const fail = (code: string): never => { throw Object.assign(new Error(code), {safeCode: code}); };
const nonEmpty = (v: unknown): v is string => typeof v === 'string' && v.length > 0;

export function requireLocale(loc: Locale): Locale {
  if (!loc || !nonEmpty(loc.key) || !nonEmpty(loc.label) || !nonEmpty(loc.chipLabel) || !nonEmpty(loc.htmlLang) || !nonEmpty(loc.timeLocale)) {
    fail('LOCALE_SCHEMA_INVALID');
  }
  for (const section of ['meta', 'chrome', 'common', 'format', 'actions', 'errors', 'drawReadiness', 'explore', 'create', 'round', 'mine', 'rules', 'dialogs', 'app'] as const) {
    if (!loc[section] || typeof loc[section] !== 'object') fail(`LOCALE_SECTION_MISSING:${section}`);
  }
  return loc;
}

export function defineLocale(loc: Locale): Locale {
  requireLocale(loc);
  const freeze = (v: unknown): void => {
    if (v && typeof v === 'object' && !Object.isFrozen(v)) {
      Object.values(v).forEach(freeze);
      Object.freeze(v);
    }
  };
  freeze(loc);
  return loc;
}
